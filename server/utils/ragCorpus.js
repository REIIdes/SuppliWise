'use strict';

const { ENTRIES, extractPmids } = require('./supplementEvidenceRegistry');
const { DOSE_TABLE } = require('./planGrounding');
const { APP_GUIDE_SECTIONS } = require('./appFeatureGuide');
const { GENERAL_SYMPTOMS, CONDITION_SYMPTOMS, MEDICAL_CONDITIONS } = require('./healthAssessmentInstrument');

/**
 * WHY THIS EXISTS.
 *
 * The chat had no knowledge of its own. Its prompt said, in as many words, "the
 * curated evidence this app is willing to stand behind is NOT available to you in
 * this conversation", and then asked the model to be useful about magnesium anyway.
 * That is the setup that produces a confident invented statistic: the model has to
 * fill the gap, and the app's only defence afterwards is the verifier deleting what
 * it wrote. Retrieval turns the order around — the app hands over the note it
 * already checked, and the model's job becomes saying that note in the member's
 * language instead of remembering one.
 *
 * Every document here comes from content the app already publishes and has already
 * verified: the evidence registry (65 entries, every PMID re-resolved against NCBI
 * by `npm run eval:citations`), the dose ceilings the plan verifier enforces, the
 * questionnaire's own option labels, and the app help text. Nothing is fetched from
 * the open web and nothing is generated by a model, which is what makes this an
 * offline, CI-runnable, keyless corpus: a knowledge base the accuracy gate can
 * depend on has to be deterministic, or "90% accurate" is a number about network
 * weather rather than about the product.
 */

const STOP = new Set(['and', 'the', 'for', 'with', 'on', 'of', 'in', 'to', 'a', 'an', 'by', 'is', 'are',
  'studies', 'study', 'supported', 'evidence', 'guidelines', 'nih', 'who', 'multiple', 'deficiency',
  'health', 'outcomes', 'quality', 'general', 'fact', 'sheet', 'society', 'office', 'dietary',
  'supplements', 'supplement', 'based', 'shows', 'show', 'research', 'trial', 'trials', 'rnd', 'rcts']);

/**
 * Fold a plural onto the stem this corpus uses.
 *
 * The order of the suffix tests and the length floor both matter. A single
 * `(ies|es|s)$` strip looks equivalent but is not: it turns "migraines" into
 * "migrain", which matches no document in this corpus, and turns "gas" into "ga".
 * The member's phrasing and the curated note must land on the SAME token or the
 * whole question scores zero — "I get migraines, what helps" retrieved nothing but
 * app help pages until this was fixed.
 *
 * Linguistic correctness is not the goal; both sides of every comparison run
 * through here, so "analysi" is fine as long as query and document agree on it.
 */
function singularize(word) {
  if (word.length < 5) return word;
  if (/ies$/.test(word)) return `${word.slice(0, -3)}y`;
  if (/(ses|xes|zes|ches|shes)$/.test(word)) return word.slice(0, -2);
  if (/s$/.test(word) && !/ss$/.test(word)) return word.slice(0, -1);
  return word;
}

function tokens(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, ' ')
    .split(/\s+/)
    .map(singularize)
    .filter((t) => t.length > 2 && !STOP.has(t));
}

function titleCase(value) {
  return String(value || '')
    .split(/\s+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

/**
 * Nutrient notes. The citation travels inside the document text on purpose: the
 * model is allowed to repeat the app's own source when it repeats the app's own
 * sentence, and `planGrounding.enforceCitationAgreement` then checks that any PMID
 * in the reply is the PMID that belongs to the nutrient it sits next to.
 */
function nutrientDocs() {
  return ENTRIES.map((entry) => ({
    id: `nutrient:${entry.nutrient}`,
    kind: 'nutrient',
    title: entry.nutrient,
    text: `${entry.nutrient} — ${entry.citation}`,
    keys: entry.keys.slice(),
    nutrients: [entry.nutrient],
    pmids: extractPmids(entry.citation).map(String),
  }));
}

/**
 * Dose notes. These are the numbers the app is willing to say out loud, taken from
 * the same table the verifier clamps against, so a chat answer and a plan row
 * cannot quote different ceilings for the same nutrient.
 */
function doseDocs() {
  return DOSE_TABLE.map((row) => {
    const name = titleCase(row.alias[0]);
    const ceiling = `${row.ceiling.value}${row.ceiling.unit}`;
    return {
      id: `dose:${name}`,
      kind: 'dose',
      title: `${name} dose`,
      text: `${name}: this app uses ${row.standard}, and ${ceiling} per day is the most it will state about ${name}. Ask a clinician about a specific amount for you, and check the Results page for the dose in your own plan.`,
      keys: row.alias.slice(),
      nutrients: [name],
      ceiling,
      pmids: [],
    };
  });
}

/**
 * Symptom and condition bridges. This is the join a member actually needs — they
 * ask about trouble sleeping, not about "magnesium" — and it is built only from
 * words the registry's own sentences contain. If the app's note for a nutrient does
 * not mention sleep, no model opinion puts it under a sleep question.
 */
function outcomeDocs(nutrients) {
  const byLabel = new Map();
  const add = (label, kind) => {
    const key = String(label || '').trim();
    if (!key || key.toLowerCase() === 'none') return;
    if (!byLabel.has(key.toLowerCase())) byLabel.set(key.toLowerCase(), { label: key, kind, hits: [] });
  };
  for (const label of GENERAL_SYMPTOMS) add(label, 'symptom');
  for (const label of CONDITION_SYMPTOMS) add(label, 'symptom');
  for (const label of MEDICAL_CONDITIONS) add(label, 'condition');

  const entryTokens = nutrients.map((doc) => ({ doc, set: new Set(tokens(doc.text)) }));
  for (const [key, row] of byLabel) {
    const labelTokens = new Set(tokens(row.label));
    if (!labelTokens.size) continue;
    for (const { doc, set } of entryTokens) {
      let shared = 0;
      for (const t of labelTokens) if (set.has(t)) shared += 1;
      if (shared > 0) row.hits.push({ nutrient: doc.title, shared, pmids: doc.pmids });
    }
    row.hits.sort((a, b) => b.shared - a.shared || a.nutrient.localeCompare(b.nutrient));
  }

  return [...byLabel.values()]
    .filter((row) => row.hits.length)
    .slice(0, 400)
    .map((row) => {
      const names = row.hits.slice(0, 5).map((h) => h.nutrient);
      return {
        id: `${row.kind}:${row.label}`,
        kind: row.kind,
        title: row.label,
        text: `"${row.label}" appears in the app's own questionnaire. The curated notes that use the same wording are: ${names.join(', ')} — each with its evidence note on the Results page. This app does not diagnose${row.kind === 'condition' ? '' : ", and a symptom worth investigating is something to raise with a clinician, not something a supplement replaces"}.`,
        keys: [row.label.toLowerCase()],
        nutrients: names,
        pmids: [],
      };
    });
}

function appDocs() {
  return APP_GUIDE_SECTIONS.map((section) => ({
    id: section.id,
    kind: 'app',
    title: section.title,
    text: `${section.title}: ${section.text}`,
    keys: section.keys.slice(),
    never: Boolean(section.never),
    nutrients: [],
    pmids: [],
  }));
}

/**
 * Field-observation notes — what the project team actually saw when it ran its research
 * interview at a community pharmacy, written down so the assistant can be honest about
 * local purchasing patterns instead of inventing them.
 *
 * The shape is deliberate, and each constraint is load-bearing:
 *
 * - `pmids: []` and `nutrients: []`. These notes carry NO evidence and name NO registry
 *   nutrient. That is not an oversight: `planGrounding` only lets a reply keep a citation
 *   that belongs to a nutrient it names, and only lets a plan row survive if the app has an
 *   evidence entry for it. A field note therefore cannot smuggle a supplement into a plan or
 *   a PMID into a sentence, and `verifyProse` still strips any number or benefit the model
 *   tries to hang on it.
 * - Every sentence states what the observation is NOT. A retrieved note reads to a member
 *   like the app's own guidance, so a note about brands has to say in the same breath that
 *   the app cannot verify those brands — otherwise the model gets a name it recognises and
 *   fills in a benefit it does not have.
 * - Composition is never guessed at. The interview recorded brand names customers ask for,
 *   not what is in them, so these notes refuse to describe them.
 *
 * Provenance: one pharmacy staff respondent, October 2026, conducted by this project. No
 * patient identifiers were collected and none are recorded here. It is a purchasing
 * pattern from one shop, not a population statement, and the note says so.
 */
function fieldStudyDocs() {
  const source = 'Source: community pharmacy staff interview conducted by the SuppliWise project team, '
    + 'October 2026 — one respondent, no patient identifiers, purchasing patterns only.';
  return [
    {
      id: 'field:maintenance-medications',
      kind: 'field',
      title: 'Maintenance medications most often bought locally',
      text: `In the community pharmacy where this app's research was conducted, the maintenance `
        + `medications customers most often buy are amlodipine, losartan and telmisartan, used for `
        + `blood pressure and cardiovascular health, and they are usually served on a prescription. `
        + `This is a note about what people around here already take, not a clinical claim: it says `
        + `nothing about whether any supplement helps blood pressure, and no supplement replaces a `
        + `prescribed antihypertensive. If a member names one of these, it is their own medication `
        + `and a clinician's decision. ${source}`,
      keys: ['amlodipine', 'losartan', 'telmisartan', 'blood pressure', 'hypertension', 'bp',
        'maintenance medication', 'prescription', 'refill', 'cardiovascular'],
      nutrients: [],
      pmids: [],
    },
    {
      id: 'field:supplement-brands',
      kind: 'field',
      title: 'Supplement brands asked for locally',
      text: `Supplement brand names frequently requested in that same pharmacy are Santonn Plus, `
        + `Santonn Plus Gold, Eyeberry, Liveraid and barley (powder or capsule). This app holds no `
        + `evidence entry for any of those brand names, so it cannot say what is in them, what dose `
        + `is right, or what they do — including for eyes, liver or any other purpose the name seems `
        + `to suggest. A brand name is not an ingredient. If a member asks about one, say the app `
        + `cannot verify that brand, and offer to talk about the ingredient list on their own pack. `
        + `${source}`,
      keys: ['santon', 'santonn', 'eyeberry', 'liveraid', 'barley', 'brand', 'sachet', 'capsule'],
      nutrients: [],
      pmids: [],
    },
    {
      id: 'field:who-was-asked',
      kind: 'field',
      title: 'Who the app was studied with',
      text: `The research this app's questionnaire was informed by was carried out in a community `
        + `pharmacy whose regular customers are mostly middle-aged and older adults, and health `
        + `shops are where many of them first ask about supplements. That is why the app writes its `
        + `plans in plain language and treats a new supplement as something to raise with the `
        + `pharmacist or clinician who already knows their medications. It is not a statement about `
        + `any individual member's risk. ${source}`,
      keys: ['research', 'interview', 'study', 'pharmacy', 'older adults', 'elderly', 'community'],
      nutrients: [],
      pmids: [],
    },
  ];
}

let cached = null;

/** The whole corpus, built once per process. Synchronous and keyless on purpose. */
function buildCorpus() {
  if (cached) return cached;
  const nutrients = nutrientDocs();
  cached = [...nutrients, ...doseDocs(), ...outcomeDocs(nutrients), ...appDocs(), ...fieldStudyDocs()];
  return cached;
}

/** Documents the route can add at query time — the member's own plan and the live learned condition bundles. */
function planDocs(assessment) {
  const rows = assessment && assessment.aiResults && Array.isArray(assessment.aiResults.recommendations)
    ? assessment.aiResults.recommendations : [];
  return rows.map((row) => {
    const name = String((row && row.name) || '').slice(0, 80);
    if (!name) return null;
    const parts = [`${name} is in this member's current plan`];
    if (row.priority) parts.push(`priority ${row.priority}`);
    if (row.dosage) parts.push(`dose ${String(row.dosage).slice(0, 60)}`);
    if (row.timing) parts.push(`timing ${String(row.timing).slice(0, 60)}`);
    if (row.reason) parts.push(String(row.reason).slice(0, 200));
    if (row.evidence) parts.push(String(row.evidence).slice(0, 200));
    return {
      id: `plan:${name.toLowerCase()}`,
      kind: 'plan',
      title: name,
      text: `${parts.join('. ')}.`,
      keys: [name.toLowerCase()],
      nutrients: [name],
      pmids: extractPmids(String(row.evidence || '')).map(String),
    };
  }).filter(Boolean);
}

/**
 * Live learned conditions (the ones the self-learning loop published through the
 * evidence gate) become documents too, so retrieval can answer about a condition the
 * app only learned recently — with the supplements its published bundle carries.
 */
function dynamicConditionDocs(live) {
  if (!Array.isArray(live)) return [];
  return live.map((c) => {
    const label = String(c.label || '').trim();
    if (!label) return null;
    const names = (c.supplements || []).map((s) => String(s.name || '').trim()).filter(Boolean);
    const symptoms = (c.symptomPool || []).map((s) => String(s || '').trim()).filter(Boolean);
    if (!names.length) return null;
    return {
      id: `condition:${label}`,
      kind: 'learned-condition',
      title: label,
      text: `${label} is a condition this app's questionnaire can ask about. Its published plan note carries ${names.slice(0, 6).join(', ')}. Symptoms the app associates with it: ${symptoms.slice(0, 8).join(', ') || 'as reported by the member'}. The app does not diagnose it, and treatment decisions stay with a clinician.`,
      keys: [label.toLowerCase()],
      nutrients: names,
      pmids: [],
    };
  }).filter(Boolean);
}

